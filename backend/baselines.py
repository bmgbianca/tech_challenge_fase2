"""Other routing approaches used only to compare against the genetic
algorithm (see backend/benchmark.py and the "Comparativo" section of the
technical report). They solve the same open-route VRP, with the same fixed
origin, the same number of cities per vehicle and the same priority deadline,
so the numbers are comparable.

- greedy_nearest_neighbor: one constructive pass, always going to the closest
  unvisited city. No search.
- best_of_random: draws many random solutions and keeps the best one (random
  search, given the same budget of evaluated solutions as the GA).
- exhaustive_search: tries every possible solution. Only feasible for very
  small instances; gives the true optimum to measure the GA against.
"""

import itertools
from typing import List

from .constants import TIME_LIMIT
from .ga import (
    InitialPopulationArgs,
    are_priorities_on_time,
    calculate_fitness,
    calculate_solution_duration,
    generate_initial_population,
    sort_population_by_fitness,
)
from .helpers.domain import get_cities_distribution
from .models import Individual, SortPopulationByFitnessArgs


def evaluate(routes: dict, individual: Individual) -> dict:
    """Total distance (km), longest vehicle duration (s) and whether every
    priority city is reached within the deadline."""

    return {
        "distance_km": calculate_fitness(routes["cities_distances"], individual),
        "duration_seconds": calculate_solution_duration(
            routes["cities_durations"], individual
        ),
        "priorities_on_time": are_priorities_on_time(
            routes["cities_durations"], individual, TIME_LIMIT
        ),
    }


def best_of_population(routes: dict, population: List[Individual]) -> Individual:
    """Best solution of a population by the same criteria used by the GA:
    valid before invalid, then the shortest distance."""

    population_fitness = [
        {
            "individual": individual,
            "total_distance": calculate_fitness(routes["cities_distances"], individual),
            "priorities_on_time": are_priorities_on_time(
                routes["cities_durations"], individual, TIME_LIMIT
            ),
        }
        for individual in population
    ]
    return sort_population_by_fitness(
        SortPopulationByFitnessArgs(
            duration_matrix=routes["cities_durations"],
            population_fitness=population_fitness,
        )
    )[0]["individual"]


def greedy_nearest_neighbor(routes, cities, origin, vehicles_number) -> Individual:
    """The first individual generated by the nearest neighbor strategy is the
    pure greedy one (always the closest city)."""

    return generate_initial_population(
        InitialPopulationArgs(
            population_strategy="nearest_neighbor",
            distances_matrix=routes["cities_distances"],
            population_size=1,
            cities=cities,
            origin_city_name=origin,
            vehicles_number=vehicles_number,
        )
    )[0]


def best_of_random(routes, cities, origin, vehicles_number, samples) -> Individual:
    population = generate_initial_population(
        InitialPopulationArgs(
            population_strategy="random",
            distances_matrix=routes["cities_distances"],
            population_size=samples,
            cities=cities,
            origin_city_name=origin,
            vehicles_number=vehicles_number,
        )
    )
    return best_of_population(routes, population)


def exhaustive_search(routes, cities, origin, vehicles_number, balanced=True):
    """Optimum of the open-route VRP by trying every solution.

    Every vehicle starts at the origin and visits at least one city. With
    balanced=True the cities are split the same way the genetic algorithm does
    (floor(n / v) per vehicle, the remainder going to the first vehicles);
    with balanced=False any split is allowed. Among the solutions that meet the
    priority deadline, returns the one with the shortest total distance (or the
    shortest overall if none meets it). Returns (individual, solutions tried)."""

    origin_city = next(city for city in cities if city["name"] == origin)
    destinations = [city for city in cities if city["name"] != origin]

    per_vehicle, remainder = get_cities_distribution(cities, True, vehicles_number)
    balanced_sizes = [
        per_vehicle + (1 if index < remainder else 0)
        for index in range(vehicles_number)
    ]

    best, best_key, tried = None, None, 0

    for order in itertools.permutations(destinations):
        if balanced:
            splits = [tuple(itertools.accumulate(balanced_sizes))[:-1]]
        else:
            splits = itertools.combinations(range(1, len(order)), vehicles_number - 1)

        for cut_points in splits:
            bounds = [0, *cut_points, len(order)]
            individual = [
                [origin_city, *order[bounds[i] : bounds[i + 1]]]
                for i in range(vehicles_number)
            ]
            tried += 1

            metrics = evaluate(routes, individual)
            key = (not metrics["priorities_on_time"], metrics["distance_km"])
            if best_key is None or key < best_key:
                best, best_key = individual, key

    return best, tried
